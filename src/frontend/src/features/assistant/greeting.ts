import { tr } from '../../lib/i18n';

/* ============================================================
   Buddy 空屏顶上那句问候。

   **必须在前端算**：按时间问候要用的是「用户现在几点」，而服务器跑在 UTC——
   北京时间早上九点在服务器上是凌晨一点，后端来算就会对着刚上班的人说「晚上好」。
   浏览器知道本地时间，这件事只能在这边做。

   顺带解决另一个歪掉的地方：问候语原先由后端拼、只有中文，而周围的卡片都走
   tr(zh, en)。演示地址已经公开，英文访客会看到一句中文问候配四张英文卡。
   ============================================================ */

/** 一天分三段。18 点之后到凌晨都算「晚上」——不为深夜单开一档，
    凌晨三点被问一句「夜深了」并不比「晚上好」更有用。 */
export function greetingFor(hour: number, name?: string | null): string {
  const who = (name ?? '').trim();
  const hello =
    hour >= 5 && hour <= 11
      ? tr('早上好', 'Good morning')
      : hour >= 12 && hour <= 17
        ? tr('下午好', 'Good afternoon')
        : tr('晚上好', 'Good evening');
  // 没名字就只问好。「早上好，」后面挂个空是比不叫名字更糟的招呼。
  if (!who) return hello;
  return tr(`${hello}，${who}`, `${hello}, ${who}`);
}
